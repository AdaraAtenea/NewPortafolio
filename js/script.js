    // Obtener formulario
    const contactForm = document.getElementById('contact-form');
    // CONFIGURACIÓN DE EMAILJS
    emailjs.init({
        publicKey: window.EMAIL_CONFIG.PUBLIC_KEY
    });
    contactForm.addEventListener('submit', async function(event) {
        event.preventDefault();
        // Obtener valores
        const name = document.getElementById('name').value.trim();
        const email = document.getElementById('email').value.trim();
        const subject = document.getElementById('subject').value.trim();
        const message = document.getElementById('message').value.trim();
        // Validar campos
        if (!name || !email || !subject || !message) {
            showNotification(translations[currentLanguage].toast_error,'error');
            return;
        }

        // Obtener botón
        const submitButton = contactForm.querySelector('button[type="submit"]');
        const originalButtonContent = submitButton.innerHTML;
        try {
            // Deshabilitar botón durante el envío
            submitButton.disabled = true;
            submitButton.innerHTML = `
                <i class="fa-solid fa-spinner fa-spin mr-2"></i>
                Enviando...
            `;
            // Enviar correo mediante EmailJS
            await emailjs.send(
                window.EMAIL_CONFIG.SERVICE_ID,
                window.EMAIL_CONFIG.TEMPLATE_ID,{
                    from_name: name,
                    from_email: email,
                    subject: subject,
                    message: message
                }
            );
            // Notificación de éxito
            showNotification(
                translations[currentLanguage].toast_success,
                'success'
            );
            // Limpiar formulario
            contactForm.reset();
        } catch (error) {
            console.error('Error al enviar el mensaje:', error);
            // Notificación de error
            showNotification(translations[currentLanguage].toast_error,'error');
        } finally {
            // Restaurar botón
            submitButton.disabled = false;
            submitButton.innerHTML = originalButtonContent;
        }
    });
